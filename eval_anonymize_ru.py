def faelle():
    out = []
    for k, (F, I, O, lat) in enumerate(LEUTE):
        for art, s in SCHABLONEN:
            w = {f"F{i}": F[i] for i in range(4)} | {f"I{i}": I[i] for i in range(4)} | {f"O{i}": O[i] for i in range(4)}
            w |= {"LAT": lat, "FIRMA": FIRMEN[k % len(FIRMEN)], "ORT": ORTE[k % len(ORTE)], "INI": f"{I[0][0]}. {O[0][0]}.", "f0": F[0].lower()}
            t = s.format(**w)
            geheim = [x for key, x in w.items() if "{" + key + "}" in s and key not in ("INI",)]
