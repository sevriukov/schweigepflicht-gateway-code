def uebermaskierung(mit_nachlese, zeige):
    k = 0
    for t in NEUTRAL:
        a, mp = anonymizer.anonymize(t, 1, ner="per")
        if mit_nachlese:
            import anon_ru
            a = anon_ru.nachlese_ru(a, mp)
            a = a[0] if isinstance(a, tuple) else a
        masken = re.findall(r"\[[^\]\n]{1,40}\]", a)
        if masken:
            k += 1
            if zeige:
                print(f"  [лишнее] {a}")
    print(f"нейтральных фраз {len(NEUTRAL)}; с лишней заменой {k} ({100 * k / len(NEUTRAL):.0f} %)")


def main():
    zeige = "--zeige" in sys.argv
    if "--neutral" in sys.argv:
        uebermaskierung(False, zeige)
        return uebermaskierung(True, zeige)
    n, miss = collections.Counter(), collections.Counter()
    for art, t, teile in faelle():
        a, _ = anonymizer.anonymize(t, 1, ner="per")
        rest = [p for p in teile if re.search(rf"(?i)(?<![\wа-яё]){re.escape(p)}(?![\wа-яё])", a)]
        n[art] += 1
        if rest:
            miss[art] += 1
            if zeige:
                print(f"  [{art}] {a}   <- осталось: {rest}")
    print(f"фраз {sum(n.values())}; с пропуском {sum(miss.values())} ({100 * sum(miss.values()) / sum(n.values()):.0f} %)")
    for art in n:
        print(f"  {art:24s} {miss[art]:2d} из {n[art]}")


if __name__ == "__main__":
    main()
